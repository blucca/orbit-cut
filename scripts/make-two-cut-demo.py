"""Build a three-shot direction exercise from the original synthetic beacon."""
import json
import os
from pathlib import Path
import subprocess
import tempfile

from PIL import Image, ImageChops

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/media'
scratch = Path(os.environ.get('ORBIT_DEMO_TEMP', ROOT / 'temp'))
scratch.mkdir(parents=True, exist_ok=True)
original = Image.open(OUT / 'shot-before.png').convert('RGB')
width, height = original.size
shifts = [0, round(width * 55 / 360), round(width * -35 / 360)]
with tempfile.TemporaryDirectory(dir=scratch) as directory:
    frames = []
    for i, shift in enumerate(shifts):
        frame = ImageChops.offset(original, shift, 0)
        assert ImageChops.difference(original, ImageChops.offset(frame, -shift, 0)).getbbox() is None
        path = Path(directory) / f'shot-{i}.png'
        frame.save(path)
        frames += ['-loop', '1', '-framerate', '24', '-t', '4', '-i', str(path)]
    subprocess.run([
        'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', *frames,
        '-f', 'lavfi', '-i', 'sine=frequency=261.6256:sample_rate=48000:duration=12',
        '-filter_complex', '[0:v][1:v][2:v]concat=n=3:v=1:a=0[v];[3:a]volume=0.04[a]',
        '-map', '[v]', '-map', '[a]', '-c:v', 'libx264', '-preset', 'veryfast',
        '-crf', '20', '-pix_fmt', 'yuv420p', '-threads', '2', '-c:a', 'aac',
        '-b:a', '96k', '-movflags', '+faststart', '-t', '12', str(OUT / 'orbit-two-cuts.mp4'),
    ], check=True)
metadata = dict(source='Original synthetic beacon, generated by scripts/make-two-cut-demo.py',
                width=width, height=height, duration_seconds=12, cut_seconds=[4, 8],
                source_shift_pixels=shifts, source_yaw_degrees=[s / width * 360 for s in shifts],
                correction_yaw_degrees=[-s / width * 360 for s in shifts])
(OUT / 'two-cuts.json').write_text(json.dumps(metadata, indent=2) + '\n')
print(json.dumps(metadata))
