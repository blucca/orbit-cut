"""Generate an original, explicitly synthetic 360-degree cut-alignment fixture.

Requires Pillow and FFmpeg; generated media is checked in for normal app builds.
"""
import json
import math
from pathlib import Path
import subprocess

from PIL import Image, ImageChops, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'public/media'
OUT.mkdir(exist_ok=True)
W, H = 2048, 1024
SHIFT = round(W * 55 / 360)
font_path = subprocess.check_output(['fc-match', 'sans', '-f', '%{file}'], text=True).strip()
font = ImageFont.truetype(font_path, 24)
small = ImageFont.truetype(font_path, 16)
im = Image.new('RGB', (W, H))
draw = ImageDraw.Draw(im)
for y in range(H):
    glow = math.exp(-((y - H * .50) / (H * .20)) ** 2)
    c = tuple(round(a + b * glow) for a, b in [(8, 29), (16, 31), (31, 28)])
    draw.line((0, y, W, y), fill=c)
for degree in range(-180, 181, 15):
    x = round((degree / 360 + .5) * W)
    draw.line((x, 200, x, 850), fill=(51, 67, 85), width=2 if degree % 45 == 0 else 1)
    if degree % 45 == 0:
        draw.text((x, 715), f'{degree:+d}°', font=font, fill=(166, 179, 192), anchor='mm')
for latitude in range(-45, 46, 15):
    y = round((.5 - latitude / 180) * H)
    draw.line((0, y, W, y), fill=(67, 78, 95), width=2 if latitude == 0 else 1)

# Asymmetric landmarks make orientation legible even away from the target.
for x, height in [(180, 70), (360, 100), (1490, 110), (1800, 55)]:
    draw.polygon([(x - 32, 665), (x, 665 - height), (x + 32, 665)], fill=(56, 80, 91))
cx, cy = W // 2, H // 2
draw.ellipse((cx - 88, cy - 88, cx + 88, cy + 88), outline='#d58b58', width=4)
draw.ellipse((cx - 67, cy - 67, cx + 67, cy + 67), fill='#eae5d6')
draw.ellipse((cx - 48, cy - 48, cx + 48, cy + 48), outline='#243247', width=3)
draw.line((cx - 30, cy, cx + 30, cy), fill='#243247', width=4)
draw.line((cx, cy - 30, cx, cy + 30), fill='#243247', width=4)
draw.text((cx, cy + 120), 'THE BEACON', font=font, fill='#eae5d6', anchor='mm')
draw.text((cx, 850), 'ORBIT CUT  /  SYNTHETIC 360° ALIGNMENT STUDY', font=small,
          fill='#a6b3c0', anchor='mm')
im.save(OUT / 'shot-before.png')
ImageChops.offset(im, SHIFT, 0).save(OUT / 'shot-after.png')
subprocess.run([
    'ffmpeg', '-hide_banner', '-loglevel', 'error', '-y',
    '-loop', '1', '-framerate', '24', '-t', '6', '-i', str(OUT / 'shot-before.png'),
    '-loop', '1', '-framerate', '24', '-t', '6', '-i', str(OUT / 'shot-after.png'),
    '-f', 'lavfi', '-i', 'sine=frequency=261.6256:sample_rate=48000:duration=12',
    '-filter_complex', '[0:v][1:v]concat=n=2:v=1:a=0[v];[2:a]volume=0.04[a]',
    '-map', '[v]', '-map', '[a]', '-c:v', 'libx264', '-preset', 'veryfast',
    '-crf', '20', '-pix_fmt', 'yuv420p', '-threads', '2', '-c:a', 'aac',
    '-b:a', '96k', '-movflags', '+faststart', '-t', '12', str(OUT / 'orbit-demo.mp4'),
], check=True)
meta = dict(source='Original synthetic fixture generated by scripts/make-demo.py',
            projection='monoscopic equirectangular 2:1', width=W, height=H,
            frames_per_second=24, duration_seconds=12, cut_seconds=6,
            reference_target_uv=[.5, .5], second_shot_horizontal_shift_pixels=SHIFT,
            nominal_heading_discontinuity_degrees=55,
            exact_heading_discontinuity_degrees=SHIFT / W * 360,
            correction_pixel_shift=-SHIFT, audio='Synthetic quiet C4 tone')
(OUT / 'demo.json').write_text(json.dumps(meta, indent=2) + '\n')
assert ImageChops.difference(im, ImageChops.offset(Image.open(OUT / 'shot-after.png'), -SHIFT, 0)).getbbox() is None
print(json.dumps(meta, indent=2))
